// Generates app/styles/type-scale.css from the handoff's type table
// (design/HANDOFF.md § 1.2, context/TYPOGRAPHY.md). Run: bun scripts/gen-type-scale.ts
// Sizes interpolate linearly between breakpoints and never go below the 360 value.

const WIDTHS = [360, 768, 1024, 1440, 1920, 2560] as const;

// px per breakpoint, in the order of WIDTHS
const SCALE: Record<string, readonly number[]> = {
  display: [64, 104, 136, 168, 200, 232],
  h1: [52, 72, 80, 96, 120, 144],
  "h1-status": [44, 56, 72, 72, 88, 104],
  h2: [48, 56, 64, 80, 104, 128],
  "h2-long": [36, 44, 48, 56, 72, 88],
  h3: [32, 40, 48, 56, 64, 72],
  h4: [24, 28, 28, 32, 40, 44],
  h5: [22, 24, 24, 28, 32, 36],
  h6: [16, 16, 16, 16, 18, 20],
  body: [16, 18, 18, 18, 20, 22],
  "body-lg": [18, 20, 20, 20, 22, 24],
  role: [16, 16, 16, 16, 18, 20],
  small: [14, 14, 14, 14, 16, 16],
  caption: [13, 13, 13, 13, 14, 15],
  button: [16, 16, 16, 16, 16, 18],
};

const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`;

function segment(i: number, v: readonly number[]): string {
  const [w0, w1] = [WIDTHS[i], WIDTHS[i + 1]];
  const [v0, v1] = [v[i], v[i + 1]];
  if (v0 === v1) return rem(v0);
  const slope = (v1 - v0) / (w1 - w0);
  const intercept = v0 - slope * w0;
  return `clamp(${rem(v0)}, calc(${rem(intercept)} + ${+(slope * 100).toFixed(4)}vw), ${rem(v1)})`;
}

const blocks: string[] = [];
for (let i = 0; i < WIDTHS.length; i++) {
  const lines: string[] = [];
  for (const [role, v] of Object.entries(SCALE)) {
    const value = i === WIDTHS.length - 1 ? rem(v[i]) : segment(i, v);
    const previous =
      i === 0 ? null : i === 1 ? segment(0, v) : segment(i - 1, v);
    // A constant segment that equals the previous one's end value needs no redefinition.
    if (i > 0 && value === rem(v[i]) && previous === value) continue;
    lines.push(`--fs-${role}: ${value};`);
  }
  if (lines.length === 0) continue;
  blocks.push(
    i === 0
      ? `:root {\n  ${lines.join("\n  ")}\n}`
      : `@media (min-width: ${WIDTHS[i] / 16}rem) {\n  :root {\n    ${lines.join("\n    ")}\n  }\n}`,
  );
}

const header =
  "/* GENERATED by scripts/gen-type-scale.ts from design/HANDOFF.md § 1.2. Do not edit by hand. */\n";
await Bun.write(
  "app/styles/type-scale.css",
  `${header}${blocks.join("\n\n")}\n`,
);
console.log("app/styles/type-scale.css written");

export {};
